import fr.elan.app.content.*
import fr.elan.app.domain.*
import java.time.*

fun runExtendedChecks(): Int {
    var count = 0
    fun t(name: String, condition: Boolean) { check(condition) { "FAIL: $name" }; count++; println("PASS: $name") }
    fun rejects(block: () -> Unit): Boolean = try { block(); false } catch (_: IllegalArgumentException) { true } catch (_: java.time.DateTimeException) { true }
    val day = LocalDate.of(2026, 10, 9)
    val base = AppSnapshot()
    t("v2 is the current schema", base.schemaVersion == 2)
    t("notifications and audio start opt-out", !base.settings.reminderEnabled && !base.settings.soundEnabled && !base.settings.voiceEnabled)
    t("48 distinct stable catalog ids", YogaCatalog.poses.map { it.id }.toSet().size == 48)
    t("original six ids preserved", setOf("seated", "cat", "child", "rest", "chair", "side").all { YogaCatalog.find(it) != null })
    t("all poses have explicit drawings", PoseSketches.all.keys == YogaCatalog.poses.map { it.id }.toSet())
    t("drawings are individually defined", PoseSketches.all.values.toSet().size == 48)
    t("drawing coordinates in canvas", PoseSketches.all.values.all { sketch ->
        (listOf(sketch.head) + sketch.strokes.flatten() + sketch.supports.flatten()).all { it.x in 0f..300f && it.y in 0f..180f }
    })
    t("every new pose has instructions and alternatives", YogaCatalog.poses.all { it.steps.size == 4 && it.steps.all { s -> s.length > 30 } && it.adaptation.isNotBlank() && it.caution.length > 25 })
    t("all three levels populated", YogaLevel.entries.all { l -> YogaCatalog.poses.any { it.level == l } })
    t("all six categories populated", YogaCategory.entries.all { c -> YogaCatalog.poses.any { it.category == c } })
    t("accent insensitive search", YogaCatalog.search("EPAULES") == YogaCatalog.search("épaules"))
    t("Sanskrit search", YogaCatalog.search("vrksasana").single().id == "tree_supported")
    t("multiword search includes equipment", YogaCatalog.search("chaise stable").any { it.id == "seated" })
    t("level filter excludes other levels", YogaCatalog.search("", YogaLevel.GENTLE).all { it.level == YogaLevel.GENTLE })
    t("category filter excludes other categories", YogaCatalog.search("", category = YogaCategory.BALANCE).all { it.category == YogaCategory.BALANCE })
    t("empty favorite filter really empty", YogaCatalog.search("", favorites = emptySet()).isEmpty())
    t("unknown query has no results", YogaCatalog.search("xxx-no-such-pose").isEmpty())
    t("blank search preserves catalog order", YogaCatalog.search("  ") == YogaCatalog.poses)
    val favorite = PracticeActions.toggleFavorite(base, "mountain")
    t("favorite added", favorite.favoritePoseIds == setOf("mountain"))
    t("favorite removed without side effects", PracticeActions.toggleFavorite(favorite, "mountain") == base)
    t("unknown favorite rejected", rejects { PracticeActions.toggleFavorite(base, "unknown") })
    t("ten curated sessions", PracticeCatalog.sessions.size == 10)
    t("curated ids unique", PracticeCatalog.sessions.map { it.id }.toSet().size == 10)
    PracticeCatalog.sessions.forEach { s ->
        val plan = PracticeCatalog.yogaPlan(s)
        t("${s.id}: all references valid", s.steps.all { YogaCatalog.find(it.poseId) != null })
        t("${s.id}: duration includes transition and prep exactly", plan.totalSeconds == s.practiceSeconds + 10 * s.steps.size)
        t("${s.id}: practice duration excludes preparation", plan.plannedSeconds == s.practiceSeconds)
        t("${s.id}: bilateral sides balanced", s.steps.groupBy { it.poseId }.all { (id, steps) ->
            if (YogaCatalog.find(id)!!.bilateral) steps.count { it.side == PoseSide.LEFT } == steps.count { it.side == PoseSide.RIGHT }
            else steps.all { it.side == PoseSide.NONE }
        })
    }
    val tree = PracticeCatalog.stepsFor("tree_supported", 45)
    t("bilateral expansion has left then right", tree.map { it.side } == listOf(PoseSide.LEFT, PoseSide.RIGHT))
    t("per-side duration retained", tree.sumOf { it.seconds } == 90)
    t("unilateral expansion remains one step", PracticeCatalog.stepsFor("seated").size == 1)
    val copy = YogaSession("custom-test", "  Test  ", "  My session  ", tree)
    val custom = PracticeActions.saveSession(base, copy)
    t("custom title trimmed", custom.customSessions.single().title == "Test")
    t("custom note trimmed", custom.customSessions.single().description == "My session")
    t("custom upsert not duplicated", PracticeActions.saveSession(custom, copy.copy(title = "Changed")).customSessions.size == 1)
    t("custom delete does not affect catalog", PracticeActions.deleteSession(custom, copy.id) == base && YogaCatalog.poses.size == 48)
    t("custom empty name refused", rejects { PracticeActions.saveSession(base, copy.copy(title = " ")) })
    t("custom empty steps refused", rejects { PracticeActions.saveSession(base, copy.copy(steps = emptyList())) })
    t("custom 41 steps refused", rejects { PracticeActions.saveSession(base, copy.copy(steps = List(41) { tree.first() })) })
    t("unknown custom pose refused", rejects { PracticeActions.saveSession(base, copy.copy(steps = listOf(YogaStep("missing", 30)))) })
    t("bilateral unspecified side refused", rejects { PracticeActions.saveSession(base, copy.copy(steps = listOf(YogaStep("tree_supported", 30)))) })
    t("unilateral labelled side refused", rejects { PracticeActions.saveSession(base, copy.copy(steps = listOf(YogaStep("seated", 30, PoseSide.LEFT)))) })
    t("curated id cannot overwrite custom", rejects { PracticeActions.saveSession(base, copy.copy(id = "morning")) })
    t("zero duration refused", rejects { YogaStep("seated", 0) })
    t("overlong duration refused", rejects { YogaStep("seated", 301) })
    val customFull = base.copy(customSessions = (0 until 30).map { copy.copy(id = "custom-$it") })
    t("31st custom session refused", rejects { PracticeActions.saveSession(customFull, copy) })
    t("editing at session limit allowed", PracticeActions.saveSession(customFull, copy.copy(id = "custom-1")).customSessions.size == 30)
    val timed = YogaSession("single", "Test", "", listOf(YogaStep("mountain", 15), YogaStep("seated", 300)))
    t("shortest scaled hold bounded to 15s", PracticeCatalog.yogaPlan(timed, 5, 50).steps.filter { it.kind == StepKind.POSE }.first().seconds == 15)
    t("longest scaled hold bounded to 300s", PracticeCatalog.yogaPlan(timed, 5, 200).steps.filter { it.kind == StepKind.POSE }.last().seconds == 300)
    t("invalid scale refused", rejects { PracticeCatalog.yogaPlan(timed, 10, 0) })
    t("zero transition refused", rejects { PracticeCatalog.yogaPlan(timed, 0) })
    t("four breathing patterns", BreathingCatalog.patterns.size == 4)
    BreathingCatalog.patterns.forEach { pattern -> listOf(1, 3, 5, 10).forEach { minutes ->
        val plan = BreathingCatalog.plan(pattern, minutes)
        t("${pattern.id} ${minutes}m: full cycles without apnea", plan.steps.drop(1).chunked(2).all { pair ->
            pair.size == 2 && pair[0].kind == StepKind.INHALE && pair[1].kind == StepKind.EXHALE
        } && plan.plannedSeconds <= minutes * 60 && minutes * 60 - plan.plannedSeconds < pattern.inhale + pattern.exhale)
    } }
    t("meditation uses actual requested duration", listOf(2, 5, 10, 15).all { BreathingCatalog.meditation(it).plannedSeconds == it * 60 })
    t("invalid meditation duration refused", rejects { BreathingCatalog.meditation(999) })
    val plan = PracticePlan("Test practice", PracticeKind.YOGA, listOf(
        TimedStep("Prepare", "", 5, StepKind.PREPARATION), TimedStep("Pose 1", "", 10, StepKind.POSE),
        TimedStep("Transition", "", 5, StepKind.TRANSITION), TimedStep("Pose 2", "", 10, StepKind.POSE)))
    val initial = PracticePlayer(plan, "record-1", day.toString())
    t("player starts paused", !initial.running && initial.actualMillis == 0L)
    var player = initial.start(1000)
    t("start idempotent", player.start(2000) == player)
    t("backwards time ignored", player.tick(0) == player)
    player = player.tick(6500)
    t("late tick crosses boundary exactly", player.index == 1 && player.remainingMillis == 9500L && player.actualMillis == 500L)
    player = player.pause(8500)
    t("pause credits elapsed work", !player.running && player.actualMillis == 2500L && player.remainingMillis == 7500L)
    t("paused tick does nothing", player.tick(900000) == player)
    player = player.start(900000).tick(912750)
    t("resume crosses pose and transition", player.index == 3 && player.actualMillis == 10250L && player.remainingMillis == 9750L)
    player = player.tick(999999)
    t("finish does not overcredit delayed tick", player.finished && !player.running && player.actualMillis == 20000L && player.elapsedMillis == 30000L)
    t("completed player needs restart", player.start(1000000) == player)
    t("restart clears accounting", player.restart() == initial)
    t("completed record exact seconds", player.record(1000)!!.actualSeconds == 20 && player.record(1000)!!.completed)
    t("empty practice not recorded", initial.record(1000) == null)
    var skipped = initial.start(100).tick(6100).skip(6100)
    t("skip never awards skipped seconds", skipped.actualMillis == 1000L && skipped.skippedPractice && skipped.index == 2)
    skipped = skipped.tick(50000)
    t("skip makes final record incomplete", skipped.actualMillis == 11000L && !skipped.record(1000)!!.completed)
    t("skipping preparation does not mark work skipped", !initial.skip(0).skippedPractice)
    t("skip while paused stays paused", !initial.skip(0).running)
    var allSkipped = initial
    repeat(4) { allSkipped = allSkipped.skip(0) }
    t("skip everything creates no false practice", allSkipped.finished && allSkipped.record(1000) == null)
    val partial = initial.start(0).pause(6250)
    t("partial record rounded down to second", partial.record(1000)!!.actualSeconds == 1 && !partial.record(1000)!!.completed)
    t("record keeps starting local date", player.record(999999)!!.date == day.toString())
    val record = player.record(1000)!!
    val history = PracticeActions.saveRecord(base, record)
    t("record persisted", history.practiceHistory.size == 1)
    t("retry cannot duplicate record", PracticeActions.saveRecord(history, record.copy(actualSeconds = 1)) == history)
    t("delete record preserves settings", PracticeActions.deleteRecord(history, record.id) == base)
    t("zero work record refused", rejects { record.copy(actualSeconds = 0) })
    t("actual over plan refused", rejects { record.copy(actualSeconds = 21) })
    t("invalid calendar date refused", rejects { record.copy(date = "2026-02-30") })
    fun recordAt(d: LocalDate, id: String, completed: Boolean = true) = record.copy(id = id, date = d.toString(), completed = completed)
    val sample = base.copy(practiceHistory = listOf(recordAt(day, "a"), recordAt(day, "b", false), recordAt(day.minusDays(1), "c"),
        recordAt(day.minusDays(6), "d"), recordAt(day.minusDays(7), "e"), recordAt(day.plusDays(1), "future")))
    t("history excludes future dates", PracticeAnalytics.history(sample, day).size == 5)
    t("seven day boundary inclusive", PracticeAnalytics.history(sample, day, 7).size == 4)
    t("kind filter works", PracticeAnalytics.history(sample, day, kind = PracticeKind.BREATHING).isEmpty())
    val stats = PracticeAnalytics.stats(PracticeAnalytics.history(sample, day))
    t("stats count active dates not rows", stats.count == 5 && stats.activeDays == 4)
    t("stats distinguish partial", stats.completedCount == 4)
    t("stats sum actual time", stats.seconds == 100L)
    t("week starts Monday", PracticeAnalytics.weekStart(day) == LocalDate.of(2026, 10, 5))
    t("week excludes past weekend", PracticeAnalytics.weekSeconds(sample, day) == 60L)
    t("consecutive today and yesterday", PracticeAnalytics.streak(sample, day) == 2)
    t("yesterday extends current streak", PracticeAnalytics.streak(sample.copy(practiceHistory = listOf(recordAt(day.minusDays(1), "y"))), day) == 1)
    t("streak ends across a gap", PracticeAnalytics.streak(base.copy(practiceHistory = listOf(recordAt(day.minusDays(2), "old"))), day) == 0)
    t("empty stats", PracticeAnalytics.stats(emptyList()) == PracticeStats(0, 0, 0, 0))
    t("invalid history window rejected", rejects { PracticeAnalytics.history(base, day, 0) })
    val paris = ZoneId.of("Europe/Paris")
    val now = day.atTime(10, 0).atZone(paris)
    t("reminder later today", nextReminder(now, 19, 0).toLocalDate() == day)
    t("reminder earlier time next day", nextReminder(now, 9, 0).toLocalDate() == day.plusDays(1))
    t("reminder equal time next day", nextReminder(now, 10, 0).toLocalDate() == day.plusDays(1))
    t("reminder keeps local hour across DST", nextReminder(ZonedDateTime.of(2026, 3, 28, 20, 0, 0, 0, paris), 19, 0).hour == 19)
    t("nonexistent spring time shifted forward", nextReminder(ZonedDateTime.of(2026, 3, 29, 0, 0, 0, 0, paris), 2, 30).hour == 3)
    t("invalid reminder hour refused", rejects { nextReminder(now, 24, 0) })
    t("duration formatting", formatDuration(65) == "1:05")
    println("Extended checks: $count")
    return count
}

